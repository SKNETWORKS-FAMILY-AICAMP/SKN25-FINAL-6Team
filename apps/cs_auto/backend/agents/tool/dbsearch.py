"""Operation DB search agent.

This module handles DB-side evidence search for CS automation.
It supports two paths:
1. fixed_sql: predefined query templates by category/pattern
2. text_to_sql: structured LLM plan -> server-side SQL rendering

Final DB search output is normalized to one shape:
{
    "decision": {...},
    "query_type": "fixed_sql" | "text_to_sql",
    "plan": {...} | None,
    "sql": "...",
    "params": (...),
    "rows": [...],
    "evidence": [...],
}
"""

